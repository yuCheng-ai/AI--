#!/usr/bin/env bash
set +x
set -euo pipefail
umask 077

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
JAR_FILE="$ROOT_DIR/backend/drama-boot/target/drama-server.jar"
PID_FILE="$ROOT_DIR/.local/run/backend.pid"
LOG_FILE="$ROOT_DIR/.local/logs/backend.log"
MIGRATE_LOG="$ROOT_DIR/.local/logs/migrate.log"
LAUNCHER_ID="drama-$(printf '%s' "$ROOT_DIR" | cksum | awk '{print $1}')"
ACTION="${1:-up}"

fail() { printf '%s\n' "$*" >&2; exit 1; }

load_env() {
  [[ -f "$ROOT_DIR/.env" ]] || "$ROOT_DIR/scripts/dev-init.sh"
  chmod 600 "$ROOT_DIR/.env"
  # .env is a trusted local configuration file generated by dev-init.sh.
  # Keep tracing off: neither source nor subsequent commands print its values.
  set +x
  set -a
  source "$ROOT_DIR/.env"
  set +a
  : "${DRAMA_DB_PASSWORD:?请设置 .env 中的 DRAMA_DB_PASSWORD}"
  : "${DRAMA_DB_APP_PASSWORD:?请设置 .env 中的 DRAMA_DB_APP_PASSWORD}"
  : "${DRAMA_DB_URL:?请设置 .env 中的 DRAMA_DB_URL}"
  : "${DRAMA_STORAGE_ROOT:?请设置 .env 中的 DRAMA_STORAGE_ROOT}"
  [[ "$DRAMA_STORAGE_ROOT" == /* ]] || fail 'DRAMA_STORAGE_ROOT 必须是绝对路径。'
  [[ "${DRAMA_HTTP_PORT:-18080}" =~ ^[0-9]+$ ]] || fail 'DRAMA_HTTP_PORT 必须是有效端口号。'
  [[ "${DRAMA_HTTP_PORT:-18080}" -ge 1 && "${DRAMA_HTTP_PORT:-18080}" -le 65535 ]] || fail 'DRAMA_HTTP_PORT 必须介于 1 和 65535。'
  mkdir -p "$DRAMA_STORAGE_ROOT" "$ROOT_DIR/.local/logs" "$ROOT_DIR/.local/run"
}

use_jdk25() {
  local candidate major detected
  local -a candidates=()
  [[ -z "${DRAMA_JAVA_HOME:-}" ]] || candidates+=("$DRAMA_JAVA_HOME")
  [[ -z "${JAVA_HOME:-}" ]] || candidates+=("$JAVA_HOME")
  if [[ -x /usr/libexec/java_home ]]; then
    detected="$(/usr/libexec/java_home -v 25 2>/dev/null || true)"
    [[ -z "$detected" ]] || candidates+=("$detected")
  fi
  candidates+=(/opt/homebrew/opt/openjdk/libexec/openjdk.jdk/Contents/Home)
  candidates+=(/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home)
  candidates+=(/usr/local/opt/openjdk/libexec/openjdk.jdk/Contents/Home)
  candidates+=(/usr/lib/jvm/java-25-openjdk /usr/lib/jvm/java-25-openjdk-amd64 /usr/lib/jvm/java-25-openjdk-arm64)
  if command -v java >/dev/null 2>&1; then
    detected="$(java -XshowSettings:properties -version 2>&1 | awk -F ' = ' '/^[[:space:]]*java.home = / {print $2; exit}')"
    [[ -z "$detected" ]] || candidates+=("$detected")
  fi
  for candidate in "${candidates[@]}"; do
    [[ -x "$candidate/bin/java" && -x "$candidate/bin/javac" ]] || continue
    major="$("$candidate/bin/java" -version 2>&1 | sed -nE 's/.*version "([0-9]+).*/\1/p' | head -n 1)"
    if [[ "$major" == 25 ]]; then
      export JAVA_HOME="$candidate"
      export PATH="$JAVA_HOME/bin:$PATH"
      DRAMA_JAVA_BIN="$JAVA_HOME/bin/java"
      return
    fi
  done
  fail '未找到 JDK 25。请安装 JDK 25，并设置 DRAMA_JAVA_HOME 或 JAVA_HOME。'
}

compose() { docker compose --project-directory "$ROOT_DIR" --env-file "$ROOT_DIR/.env" -f "$ROOT_DIR/compose.yaml" "$@"; }

start_database() {
  command -v docker >/dev/null 2>&1 || fail '未找到 Docker。'
  docker info >/dev/null 2>&1 || fail 'Docker 尚未启动。'
  printf '启动本项目 PostgreSQL（127.0.0.1:15432）…\n'
  compose up -d --wait --wait-timeout 90 postgres
}

build_backend() {
  if process_is_ours; then
    fail '后端正在运行。请先运行 ./scripts/backend.sh stop，再构建，避免替换进程正在读取的 JAR。'
  fi
  use_jdk25
  local maven
  if [[ -x "$ROOT_DIR/backend/mvnw" ]]; then
    maven="$ROOT_DIR/backend/mvnw"
  elif command -v mvn >/dev/null 2>&1; then
    maven="$(command -v mvn)"
  else
    fail 'Maven Wrapper 不可执行，且未找到 Maven。请恢复 backend/mvnw 的可执行权限。'
  fi
  printf '使用 JDK 25 构建后端（不编译或运行测试）…\n'
  env -u DRAMA_DB_PASSWORD -u DRAMA_DB_APP_PASSWORD -u DRAMA_BOOTSTRAP_PASSWORD \
    "$maven" -B -ntp -f "$ROOT_DIR/backend/pom.xml" -Dmaven.test.skip=true clean package
  [[ -f "$JAR_FILE" ]] || fail '构建未生成 backend/drama-boot/target/drama-server.jar。'
}

require_jar() { [[ -f "$JAR_FILE" ]] || fail '缺少可执行 JAR，请先运行 ./scripts/backend.sh build。'; }

run_migration() {
  use_jdk25
  require_jar
  printf '以 drama_owner 执行一次性数据库迁移…\n'
  if ! (cd "$ROOT_DIR" && env -u DRAMA_BOOTSTRAP_PASSWORD DRAMA_BOOTSTRAP_ENABLED=false \
    "$DRAMA_JAVA_BIN" -Duser.timezone=UTC -jar "$JAR_FILE" --spring.profiles.active=migrate) > "$MIGRATE_LOG" 2>&1; then
    fail "迁移失败；请检查 $MIGRATE_LOG（脚本不会自动输出日志）。"
  fi
  printf '迁移已完成。日志：%s\n' "$MIGRATE_LOG"
}

read_pid() {
  [[ -f "$PID_FILE" ]] || return 1
  DRAMA_PID="$(cat "$PID_FILE")"
  [[ "$DRAMA_PID" =~ ^[1-9][0-9]*$ ]] || return 1
}

process_is_ours() {
  local process_command
  read_pid || return 1
  kill -0 "$DRAMA_PID" 2>/dev/null || return 1
  process_command="$(ps -p "$DRAMA_PID" -o command= 2>/dev/null || true)"
  [[ "$process_command" == *"-Ddrama.launcherId=$LAUNCHER_ID "* && "$process_command" == *"$JAR_FILE"* ]]
}

start_backend() {
  if process_is_ours; then
    printf '后端已在运行，PID=%s；日志：%s\n' "$DRAMA_PID" "$LOG_FILE"
    return
  fi
  use_jdk25
  require_jar
  command -v curl >/dev/null 2>&1 || fail '需要 curl 检查启动就绪。'
  if [[ "${DRAMA_BOOTSTRAP_ENABLED:-true}" == true ]]; then
    : "${DRAMA_BOOTSTRAP_USERNAME:?请设置初始管理员用户名}"
    : "${DRAMA_BOOTSTRAP_PASSWORD:?请设置初始管理员密码}"
  fi
  if command -v lsof >/dev/null 2>&1 && lsof -nP -iTCP:"${DRAMA_HTTP_PORT:-18080}" -sTCP:LISTEN >/dev/null 2>&1; then
    fail "端口 ${DRAMA_HTTP_PORT:-18080} 已被占用；未停止或修改其他进程。"
  fi
  [[ ! -f "$LOG_FILE" ]] || mv "$LOG_FILE" "$LOG_FILE.$(date +%Y%m%d-%H%M%S)"
  (
    cd "$ROOT_DIR"
    # The API process never receives the owner password used for DDL migrations.
    nohup env -u DRAMA_DB_PASSWORD DRAMA_BOOTSTRAP_ENABLED="${DRAMA_BOOTSTRAP_ENABLED:-true}" \
      "$DRAMA_JAVA_BIN" "-Ddrama.launcherId=$LAUNCHER_ID" -Duser.timezone=UTC -jar "$JAR_FILE" \
      > "$LOG_FILE" 2>&1 < /dev/null &
    printf '%s\n' "$!" > "$PID_FILE"
  )
  local attempt
  for ((attempt = 0; attempt < 60; attempt++)); do
    process_is_ours || fail "后端进程已退出；请检查 $LOG_FILE。"
    if curl --fail --silent --max-time 2 "http://127.0.0.1:${DRAMA_HTTP_PORT:-18080}/actuator/health/readiness" >/dev/null; then
      printf '后端已就绪，PID=%s\n' "$DRAMA_PID"
      printf 'Swagger：http://127.0.0.1:%s/swagger-ui/index.html\n' "${DRAMA_HTTP_PORT:-18080}"
      printf '日志：%s\n' "$LOG_FILE"
      return
    fi
    sleep 1
  done
  fail "等待就绪超时；进程仍受 PID 文件管理，请检查 $LOG_FILE 或运行 ./scripts/backend.sh stop。"
}

stop_backend() {
  if ! process_is_ours; then
    printf '没有通过本脚本启动的后端进程；未操作其他进程。\n'
    return
  fi
  printf '停止本项目后端，PID=%s…\n' "$DRAMA_PID"
  kill -TERM "$DRAMA_PID"
  local attempt
  for ((attempt = 0; attempt < 45; attempt++)); do
    if ! process_is_ours; then
      rm -f "$PID_FILE"
      printf '后端已停止，数据库和数据保留。\n'
      return
    fi
    sleep 1
  done
  fail '后端尚未退出；保留 PID 文件，请检查日志。未发送强制终止信号。'
}

show_status() {
  if process_is_ours; then
    printf '本地 API：运行中，PID=%s\n' "$DRAMA_PID"
  else
    printf '本地 API：未运行（不包括通过 Compose 启动的 API）。\n'
  fi
  if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
    compose ps
  else
    printf 'Docker：不可用。\n'
  fi
  printf 'Swagger：http://127.0.0.1:%s/swagger-ui/index.html\n' "${DRAMA_HTTP_PORT:-18080}"
}

case "$ACTION" in
  build) load_env; build_backend ;;
  migrate) load_env; run_migration ;;
  start) load_env; start_backend ;;
  stop) stop_backend ;;
  status) load_env; show_status ;;
  up)
    load_env
    if process_is_ours; then
      show_status
      printf '已有实例正在运行。更新代码后请先 stop，再运行 up。\n'
    else
      start_database
      build_backend
      run_migration
      start_backend
    fi
    ;;
  *) printf '用法：./scripts/backend.sh [up|build|migrate|start|stop|status]\n' >&2; exit 2 ;;
esac
